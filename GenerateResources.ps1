param(
    [string]$ResourceRoot = "resources_ViewPoint",
    [string]$OutputRc = "ViewPointResources.generated.rc",
    [string]$OutputRes = "ViewPointResources.res"
)

$ErrorActionPreference = "Stop"

# --------------------------------------------------
# Check resource directory
# --------------------------------------------------

if (!(Test-Path -LiteralPath $ResourceRoot -PathType Container)) {
    throw "Resource directory not found: $ResourceRoot"
}

$root = (Resolve-Path -LiteralPath $ResourceRoot).Path

# --------------------------------------------------
# Find all supported assets
# --------------------------------------------------

$files = @(
    Get-ChildItem -LiteralPath $root -Recurse -File |
    Where-Object {
        $_.Extension.ToLowerInvariant() -in @(
            ".obj",
            ".mtl",
            ".png"
        )
    } |
    Sort-Object FullName
)

if ($files.Count -eq 0) {
    throw "No OBJ, MTL or PNG files found."
}

# --------------------------------------------------
# Generate RC file
# --------------------------------------------------

$rcLines = @(
    "// Automatically generated by GenerateResources.ps1"
)

foreach ($file in $files) {

    # Relative path inside resources_ViewPoint
    $relative = $file.FullName.Substring(
        $root.Length
    ).TrimStart('\', '/')

    # Resource name must match the C++ asset path
    $resourceName = $relative.Replace('\', '/')

    # Forward slashes avoid Windows path escaping issues
    $resourceFile = $file.FullName.Replace('\', '/')

    $rcLines += '"' + $resourceName + '" RCDATA "' + $resourceFile + '"'
}

# --------------------------------------------------
# Save generated RC
# --------------------------------------------------

Set-Content `
    -LiteralPath $OutputRc `
    -Value $rcLines `
    -Encoding ASCII

Write-Host "Generated resource script: $OutputRc"

# --------------------------------------------------
# Compile Windows resources
# --------------------------------------------------

& rc.exe /nologo /fo $OutputRes $OutputRc

if ($LASTEXITCODE -ne 0) {
    throw "Resource compilation failed: $LASTEXITCODE"
}

Write-Host ""
Write-Host "Resource compilation successful."
Write-Host "Embedded files: $($files.Count)"
Write-Host "Output: $OutputRes"

Write-Host "=== Generated resource script ==="
Get-Content ViewPointResources.rc

Write-Host "=== Compiled resource file ==="
Get-Item ViewPointResources.res | Format-List FullName, Length

if ((Get-Item ViewPointResources.res).Length -eq 0) {
    throw "ViewPointResources.res is empty"
}

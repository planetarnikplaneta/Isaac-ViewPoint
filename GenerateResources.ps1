
param(
    [string]$ResourceRoot = "resources_ViewPoint",
    [string]$OutputRc = "ViewPointResources.generated.rc",
    [string]$OutputRes = "ViewPointResources.res"
)

$ErrorActionPreference = "Stop"

if (!(Test-Path -LiteralPath $ResourceRoot -PathType Container)) {
    throw "Resource directory not found: $ResourceRoot"
}

$root = (Resolve-Path -LiteralPath $ResourceRoot).Path

$files = @(
    Get-ChildItem -LiteralPath $root -Recurse -File |
    Where-Object {
        $_.Extension.ToLowerInvariant() -in @(".obj", ".mtl", ".png")
    } |
    Sort-Object FullName
)

if ($files.Count -eq 0) {
    throw "No supported assets found in $root"
}

$rcLines = @(
    "// Automatically generated by GenerateResources.ps1"
)

$resourceNames = @()

foreach ($file in $files) {
    $relative = $file.FullName.Substring($root.Length).TrimStart('\', '/')
    $resourceName = $relative.Replace('\', '/')
    $resourceFile = $file.FullName.Replace('\', '/')

    $resourceNames += $resourceName

    $rcLines += '"' + $resourceName + '" RCDATA "' + $resourceFile + '"'

    Write-Host "Embedding: $resourceName"
}

if ($resourceNames -notcontains "objects/sphere.obj") {
    throw "Expected asset objects/sphere.obj was not found."
}

Set-Content -LiteralPath $OutputRc -Value $rcLines -Encoding ASCII

Write-Host "`nGenerated RC:"
Get-Content -LiteralPath $OutputRc

Write-Host "`nCompiling resources..."

& rc.exe /nologo /fo $OutputRes $OutputRc

if ($LASTEXITCODE -ne 0) {
    throw "rc.exe failed with exit code $LASTEXITCODE"
}

if (!(Test-Path -LiteralPath $OutputRes)) {
    throw "Resource output was not created."
}

$res = Get-Item -LiteralPath $OutputRes

if ($res.Length -le 0) {
    throw "Resource output is empty."
}

Write-Host "`nResource compilation successful."
Write-Host "Embedded asset count: $($files.Count)"
Write-Host "Resource file size: $($res.Length) bytes"
